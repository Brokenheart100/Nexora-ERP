async function txt(id) { return (await page.getByTestId(id).first().innerText()).trim() }
async function bodyText(id) { return (await page.getByTestId(id).first().innerText()).replace(/\s+/g, ' ').trim() }
async function shot(name) {
  await page.waitForTimeout(300)
  await page.screenshot({ path: path.join(OUT, name + '.png'), fullPage: false })
  console.log('SHOT ' + name)
}
async function pick(id, option) {
  await page.getByTestId(id).click()
  await page.waitForTimeout(250)
  await page.locator('[role="option"]').filter({ hasText: option }).last().click()
  await page.waitForTimeout(250)
}
async function choose(id, option) {
  const select = page.getByTestId(id)
  await select.scrollIntoViewIfNeeded()
  await select.focus()
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  await page.keyboard.press('ArrowDown')
  await page.waitForTimeout(450)
  await page.locator('[role="option"]').filter({ hasText: option }).last().click()
  await page.waitForTimeout(450)
}
async function openRoot(url, id) {
  await page.goto(BASE + url, { waitUntil: 'domcontentloaded' })
  await page.getByTestId(id).waitFor({ state: 'visible', timeout: 25000 })
  await page.waitForTimeout(1200)
}
async function openTab(rootId, label) {
  await page.getByTestId(rootId).getByText(label, { exact: true }).first().click()
  await page.waitForTimeout(600)
}
async function downloadText(id) {
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByTestId(id).click()])
  const file = await download.path()
  return { name: download.suggestedFilename(), text: file ? fs.readFileSync(file, 'utf8') : '' }
}
async function closeOverlay() {
  await page.keyboard.press('Escape')
  await page.waitForTimeout(350)
}

