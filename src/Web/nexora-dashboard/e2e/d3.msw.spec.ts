test('D3 映射提交丢失响应后刷新回读，明确重放原键与原请求', async ({ page }) => {
  await login(page, '/finance?tab=documents', 'finance-unknown')
  await expect(page.getByTestId('finance-trade-setup')).toBeVisible({ timeout: 45_000 })
  await fillMapping(page, 'trade', tradeMappingFields)
  const writes: { key: string, body: string | null }[] = []
  page.on('request', (request) => {
    if (request.method() === 'POST' && new URL(request.url()).pathname.endsWith('/trade/setup')) writes.push({ key: request.headers()['idempotency-key']!, body: request.postData() })
  })
  await page.getByTestId('finance-save-trade').click()
  await expect(page.getByTestId('finance-mapping-trade-feedback')).toContainText('结果待确认')
  expect(writes).toHaveLength(1)
  await page.reload()
  const feedback = page.getByTestId('finance-mapping-trade-feedback')
  await feedback.getByRole('button', { name: '恢复上次提交', exact: true }).click()
  await feedback.getByRole('button', { name: '查询当前配置', exact: true }).click()
  await expect(feedback.getByRole('button', { name: '重试原提交', exact: true })).toBeEnabled()
  await feedback.getByRole('button', { name: '重试原提交', exact: true }).click()
  await expect(page.getByTestId('finance-save-trade')).toBeDisabled()
  await expect(feedback).not.toBeVisible()
  expect(writes).toHaveLength(2)
  expect(writes[1]).toEqual(writes[0])
})

