async function fillMapping(page: Page, area: string, fields: MappingField[]) {
  for (const field of fields.filter(value => !value.optional)) {
    await page.getByTestId(`finance-${area}-${field.key}`).click()
    await page.getByRole('option', { name: new RegExp(field.label + '$') }).click()
  }
}

