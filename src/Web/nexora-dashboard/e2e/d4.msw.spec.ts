import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, path = '/purchase-orders', scenario = 'd4') {
  await page.goto(path + (path.includes('?') ? '&' : '?') + 'mockCase=' + scenario)
  await expect(page.getByTestId('user-menu-trigger')).toContainText('未登录', { timeout: 45_000 })
  await page.getByTestId('user-menu-trigger').click()
  await page.getByRole('menuitem', { name: '登录 Nexora', exact: true }).click()
}
async function fillOrder(page: Page, number: string) {
  await page.getByTestId('orders-create').click()
  await page.getByTestId('order-form-number').fill(number)
  await page.getByTestId('order-form-supplier').click()
  await page.getByRole('option', { name: /MSW-SUP MSW 演示供应商/ }).click()
  await page.getByTestId('order-form-expected').fill('2026-01-03')
  await page.getByTestId('order-form-line-item').click()
  await page.getByRole('option', { name: 'MSW-SKU-001 MSW 演示商品', exact: true }).click()
}
async function create(page: Page, number: string) {
  await fillOrder(page, number)
  await page.getByTestId('order-form-line-qty').fill('9007199254740993.000001')
  await expect(page.getByTestId('order-form-line-qty')).toHaveValue('9007199254740993.000001')
  await page.getByTestId('order-form-line-qty').fill('100')
  await page.getByTestId('order-form-line-price').fill('10')
  await page.getByTestId('order-form-save-draft').click()
}

test('D4 采购单价校验保留输入并拦截不合格的请求', async ({ page }) => {
  await login(page)
  await fillOrder(page, 'D4-MSW-PRICE')
  const prices: string[] = []
  const isCreation = (method: string, url: string) => method === 'POST' && new URL(url).pathname.endsWith('/orders')
  page.on('request', (request) => {
    if (isCreation(request.method(), request.url())) prices.push(request.postDataJSON().draft.lines[0].unitPrice)
  })

  const price = page.getByTestId('order-form-line-price')
  await expect(price).toHaveValue('')
  for (const invalid of ['0', '0.0000001', '10000000.000001']) {
    await price.fill(invalid)
    await page.getByTestId('order-form-save-draft').click()
    await expect(page.getByTestId('order-form-error')).toContainText('第 1 行 · 单价须大于 0')
    await expect(price).toHaveValue(invalid)
    expect(prices).toHaveLength(0)
  }
  await price.fill('10.123456')
  const saved = page.waitForResponse(response => isCreation(response.request().method(), response.url()))
  await page.getByTestId('order-form-save-draft').click()
  expect((await saved).status()).toBe(201)
  await expect(page.getByTestId('order-form')).not.toBeVisible()
  expect(prices).toEqual(['10.123456'])
})

test('D4 采购读取被拒绝时显示工作区权限提示并重新读取授权', async ({ page }) => {
  await login(page, '/catalog')
  await expect(page.getByTestId('catalog-table')).toBeVisible()
  await page.goto('/purchase-orders?mockCase=read-only')
  const denied = page.getByTestId('orders-state-forbidden')
  await expect(denied).toContainText('当前账号在此工作区没有采购订单读取权限。')
  await expect(denied).not.toContainText('?state=forbidden')
  await expect(page.getByTestId('orders-create')).toBeDisabled()

  const access = page.waitForResponse(response => /\/bff\/api\/workspaces\/[^/]+\/access$/.test(new URL(response.url()).pathname))
  await denied.getByRole('button', { name: '刷新权限', exact: true }).click()
  expect((await access).ok()).toBe(true)
  await expect(page).toHaveURL(/mockCase=read-only/)
  await expect(denied).toBeVisible()
})

