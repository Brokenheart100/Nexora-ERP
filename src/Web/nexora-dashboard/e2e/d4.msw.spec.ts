test('D4 原采购创建丢失响应，刷新后回读并明确重放原提交', async ({ page }) => {
  await login(page, '/purchase-orders', 'd4-order-unknown')
  await create(page, 'D4-MSW-UNKNOWN')
  await expect(page.getByTestId('purchase-recovery-order')).toContainText('结果待确认')
  await page.reload()
  const recovery = page.getByTestId('purchase-recovery-order')
  await recovery.getByRole('button', { name: '恢复上次提交', exact: true }).click()
  await expect(page.getByTestId('order-form-number')).toHaveValue('D4-MSW-UNKNOWN')
  // Recovery controls remain outside the drawer; close it without discarding the frozen submission.
  await page.getByTestId('order-form-cancel').click()
  await recovery.getByRole('button', { name: '读取当前状态', exact: true }).click()
  await recovery.getByRole('button', { name: '重试原提交', exact: true }).click()
  await expect(recovery).not.toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: 'D4-MSW-UNKNOWN' })).toHaveCount(1)
})

